"""
scripts/export_to_c.py
=========================
Extracts the trained policy network's weights into a plain C header file,
with a hand-written forward-pass function. No TFLite Micro, no ONNX
runtime, no dependencies at all beyond standard C math, this runs on
essentially any microcontroller (ESP32, STM32, Arduino) as-is.

USAGE
-----
    python scripts/export_to_c.py --model checkpoints/furuta/furuta_final.zip --out furuta_policy.h

Then in your embedded project:
    #include "furuta_policy.h"
    float obs[4] = {theta, theta_dot, alpha, alpha_dot};   // radians, rad/s
    float action = furuta_policy_forward(obs);              // in [-1, 1]
    // apply: motor_command = action * MAX_TORQUE
"""

import argparse

import numpy as np
from stable_baselines3 import SAC


def extract_layers(actor):
    layers = []
    for module in actor.latent_pi:
        if hasattr(module, "weight"):
            w = module.weight.detach().cpu().numpy()
            b = module.bias.detach().cpu().numpy()
            layers.append((w, b, "relu"))
    w = actor.mu.weight.detach().cpu().numpy()
    b = actor.mu.bias.detach().cpu().numpy()
    layers.append((w, b, "tanh"))
    return layers


def format_c_array(name, arr):
    flat = arr.flatten()
    values = ", ".join(f"{v:.8f}f" for v in flat)
    return f"static const float {name}[{flat.size}] = {{ {values} }};"


def generate_header(layers, obs_dim):
    lines = [
        "// Auto-generated by scripts/export_to_c.py, do not edit by hand.",
        "// Regenerate from a newly trained model instead.",
        "#ifndef FURUTA_POLICY_H",
        "#define FURUTA_POLICY_H",
        "",
        "#include <math.h>",
        "",
        f"#define FURUTA_OBS_DIM {obs_dim}",
        "",
    ]

    for i, (w, b, _) in enumerate(layers):
        out_dim, in_dim = w.shape
        lines.append(f"// Layer {i}: {in_dim} -> {out_dim}")
        lines.append(format_c_array(f"W{i}", w))
        lines.append(format_c_array(f"B{i}", b))
        lines.append("")

    lines.append("static void _furuta_layer(const float *in, int in_dim, const float *W, "
                  "const float *B, int out_dim, float *out, int use_relu) {")
    lines.append("    for (int o = 0; o < out_dim; o++) {")
    lines.append("        float sum = B[o];")
    lines.append("        for (int i = 0; i < in_dim; i++) sum += W[o * in_dim + i] * in[i];")
    lines.append("        out[o] = use_relu ? (sum > 0.0f ? sum : 0.0f) : sum;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("// obs = [theta, theta_dot, alpha, alpha_dot], radians and rad/s.")
    lines.append("// Returns the action in [-1, 1], multiply by your max torque/voltage.")
    lines.append("static float furuta_policy_forward(const float *obs) {")
    lines.append(f"    float buf_a[{max(w.shape[0] for w, _, _ in layers)}];")
    lines.append(f"    float buf_b[{max(w.shape[0] for w, _, _ in layers)}];")
    lines.append("    const float *cur_in = obs;")
    lines.append("    float *cur_out = buf_a;")
    lines.append("    float *other = buf_b;")
    lines.append("")

    for i, (w, b, act) in enumerate(layers):
        out_dim, in_dim = w.shape
        use_relu = "1" if act == "relu" else "0"
        in_dim_expr = "FURUTA_OBS_DIM" if i == 0 else str(layers[i - 1][0].shape[0])
        lines.append(f"    _furuta_layer(cur_in, {in_dim_expr}, W{i}, B{i}, {out_dim}, cur_out, {use_relu});")
        if i < len(layers) - 1:
            lines.append("    cur_in = cur_out;")
            lines.append("    { float *tmp = cur_out; cur_out = other; other = tmp; }")
        lines.append("")

    lines.append("    return cur_out[0];  // single action output, already tanh-squashed to [-1, 1]")
    lines.append("}")
    lines.append("")
    lines.append("#endif // FURUTA_POLICY_H")

    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True, help="Path to a trained SAC model .zip")
    ap.add_argument("--out", default="furuta_policy.h")
    args = ap.parse_args()

    model = SAC.load(args.model, device="cpu")
    actor = model.policy.actor
    layers = extract_layers(actor)

    obs_dim = model.observation_space.shape[0]
    header = generate_header(layers, obs_dim)

    with open(args.out, "w") as f:
        f.write(header)

    total_params = sum(w.size + b.size for w, b, _ in layers)
    print(f"Exported {len(layers)} layer(s), {total_params} parameters, to {args.out}")
    print("Include it in your embedded project and call furuta_policy_forward(obs).")
    print("Remember: this is the POLICY only. Your firmware still needs to read the")
    print("encoders into [theta, theta_dot, alpha, alpha_dot], call the policy, and")
    print("convert the returned action into an actual motor command, at a fixed")
    print("control loop rate matching roughly what dt was during training (10ms here).")


if __name__ == "__main__":
    main()
